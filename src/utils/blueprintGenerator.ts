export async function exportZipBundle(config: DevPhoneConfig): Promise<Blob> {
  const zip = new JSZip();
  const files = getAllBlueprintFiles(config);

  for (const file of files) {
    zip.file(file.filename, file.content);
  }

  // Add README explaining low-power device usage
  const readmeContent = `# ${config.projectName} (${config.codename}) Blueprint Bundle
## Engineered for Low-Power Devices & Cloud-Assisted Building

Congratulations! This bundle contains the complete visual and technical specification for your custom Android 17 developer phone.

### Why this exists:
Building an Android 17 ROM locally requires 64GB+ RAM, 16 CPU cores, and over 350GB of disk space. For developers working on low-spec hardware (Chromebooks, Raspberry Pi, netbooks, or mobile devices), local compilation is impossible.

### How to use this blueprint bundle:
1. **Cloud Compilation via GitHub Actions**:
   - Push this directory or the \`.github/workflows/build-devphone17.yml\` to your GitHub repository.
   - Go to Actions -> 'DroidForge 17 Remote Cloud Builder' -> 'Run workflow'.
   - GitHub's cloud runners will execute the entire 6-hour build and publish ready-to-flash \`boot.img\` and \`super.img\` directly to your Releases page!

2. **Zero-Compile Flashing on Weak Devices**:
   - Download the generated fastboot image zip to your low-power device.
   - Connect your phone via USB-C.
   - Run \`bash scripts/flash-blueprint.sh\` (Linux/macOS/ChromeOS/Termux) or \`scripts\\flash-blueprint.bat\` (Windows).
   - Your device is flashed with your custom Android 17 ROM in under 90 seconds!

### Included Manifests & Trees:
- \`manifest.xml\`: AOSP Repo Manifest
- \`device/devphone/${config.codename}/\`: Device tree and BoardConfig.mk
- \`specs/SPEC-SHEET.md\`: Hardware engineering specification
- \`specs/HARDWARE-PINOUTS.md\`: UART & Pogo pinout guide
- \`schematics/devphone17-schematic.svg\`: Vector CAD blueprint diagram

Generated by DroidForge 17 Studio.
`;

  zip.file('README.md', readmeContent);

  return await zip.generateAsync({ type: 'blob' });
}
